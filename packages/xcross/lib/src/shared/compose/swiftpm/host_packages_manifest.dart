import 'package:meta/meta.dart';
import 'package:xcross/src/shared/compose/swiftpm/swift_package_model.dart';

/// Default product/target name of the aggregate package.
@internal
const defaultHostPackagesProductName = 'XcrossHostPackages';

/// The aggregate package's files, relative to its root.
@internal
final class HostPackagesManifest {
  const HostPackagesManifest({
    required this.packageSwift,
    required this.sources,
  });

  /// The `Package.swift` text.
  final String packageSwift;

  /// Relative path (POSIX) to content of every generated source file.
  final Map<String, String> sources;

  /// [packageSwift] plus [sources], keyed by relative path.
  Map<String, String> get allFiles => {
    'Package.swift': packageSwift,
    ...sources,
  };
}

/// Generates a dynamic-library package that depends on every product the
/// host links, so `swift build` produces one library to link the host with.
@internal
HostPackagesManifest generateHostPackagesManifest({
  required HostSwiftPackages packages,
  required String deploymentTarget,
  String productName = defaultHostPackagesProductName,
}) {
  final name = swiftStringLiteral(productName);
  // `packages.packages` is already unique and sorted by identity.
  final declarations = [
    for (final pkg in packages.packages) pkg.manifestDeclaration,
  ];
  final products = [
    for (final product in packages.products)
      _productDependency(product.productName, product.package.identity),
  ];

  String list(List<String> items, String indent) => items.isEmpty
      ? '[]'
      : '[\n${items.map((i) => '$indent    $i,\n').join()}$indent]';

  final packageSwift =
      '''
// swift-tools-version:5.9
// Generated by xcross. Do not edit.
import PackageDescription

let package = Package(
    name: $name,
    platforms: [.iOS(${swiftStringLiteral(deploymentTarget)})],
    products: [
        .library(name: $name, type: .dynamic, targets: [$name]),
    ],
    dependencies: ${list(declarations, '    ')},
    targets: [
        .target(
            name: $name,
            dependencies: ${list(products, '            ')},
            path: ${swiftStringLiteral('Sources/$productName')}
        ),
    ]
)
''';
  return HostPackagesManifest(
    packageSwift: packageSwift,
    sources: {
      'Sources/$productName/$productName.swift':
          '// Generated by xcross: links the Swift packages the SwiftUI host '
          'uses.\n',
    },
  );
}

String _productDependency(String name, String package) =>
    '.product(name: ${swiftStringLiteral(name)}, '
    'package: ${swiftStringLiteral(package)})';
